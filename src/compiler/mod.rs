use crate::parser::{Function, Instruction, Operand, Program};

pub use instruction::{CompileError, Writer};
use specialized::encode;

pub use linker::{Module, Plugin, link};

#[derive(Debug, Clone)]
pub struct CompiledFunction {
    pub name: String,
    pub params: u8,
    pub captures: u8,
    pub bytecode: Vec<u8>,
}

pub fn compile(p: &Program) -> Result<Vec<CompiledFunction>, CompileError> {
    let mut out = Vec::new();
    for f in &p.functions {
        out.push(compile_function(f)?);
    }
    Ok(out)
}

/// Run instruction validation without retaining generated bytecode.
/// Each instruction is checked independently so a malformed instruction does
/// not hide later errors in the same function.
pub fn validate(p: &Program) -> Vec<CompileError> {
    let mut errors = Vec::new();
    for f in &p.functions {
        let mut ins = f.instructions.clone();
        if ins.last().is_none_or(|i| i.name != "ret") {
            ins.push(Instruction {
                name: "ret".into(),
                operands: vec![Operand::Register(255)],
                line: 0,
                column: 0,
                operand_columns: vec![0],
            });
        }
        let count = ins.len();
        let placeholder_offsets = vec![0; count + 1];
        for (ix, instruction) in f.instructions.iter().enumerate() {
            let mut writer = Writer::default();
            if let Err(mut error) = encode(instruction, &mut writer, ix, &placeholder_offsets, true)
            {
                error.line = instruction.line as i32;
                errors.push(error);
            }
        }

        // Measure encoded instruction widths without retaining or assembling
        // function bytecode, then apply the same relative-jump range check.
        let mut offsets = vec![0; count + 1];
        let mut measurement_failed = false;
        for (ix, instruction) in ins.iter().enumerate() {
            let mut writer = Writer::default();
            if encode(instruction, &mut writer, ix, &placeholder_offsets, true).is_err() {
                measurement_failed = true;
                break;
            }
            offsets[ix + 1] = offsets[ix] + writer.data.len();
        }
        if !measurement_failed {
            for (ix, instruction) in ins.iter().enumerate() {
                if !matches!(instruction.name.as_str(), "jmp" | "jmp_if" | "jmp_if_not") {
                    continue;
                }
                let Some(Operand::Number(_)) = instruction.operands.first() else {
                    continue;
                };
                let mut writer = Writer::default();
                if let Err(mut error) = encode(instruction, &mut writer, ix, &offsets, false) {
                    if error.message.contains("Jump byte offset") {
                        error.line = instruction.line as i32;
                        errors.push(error);
                    }
                }
            }
        }
    }
    errors
}

fn compile_function(f: &Function) -> Result<CompiledFunction, CompileError> {
    let mut ins = f.instructions.clone();
    if ins.last().is_none_or(|i| i.name != "ret") {
        ins.push(Instruction {
            name: "ret".into(),
            operands: vec![Operand::Register(255)],
            line: 0,
            column: 0,
            operand_columns: vec![0],
        });
    }
    let mut offsets = vec![0; ins.len() + 1];
    let mut measure = Writer::default();
    for (ix, i) in ins.iter().enumerate() {
        offsets[ix] = measure.data.len();
        encode(i, &mut measure, ix, &offsets, true).map_err(|mut e| {
            e.line = i.line as i32;
            e
        })?;
    }
    offsets[ins.len()] = measure.data.len();
    let mut w = Writer::default();
    for (ix, i) in ins.iter().enumerate() {
        encode(i, &mut w, ix, &offsets, false).map_err(|mut e| {
            e.line = i.line as i32;
            e
        })?;
    }
    Ok(CompiledFunction {
        name: f.name.clone(),
        params: f.params,
        captures: f.captures,
        bytecode: w.data,
    })
}
