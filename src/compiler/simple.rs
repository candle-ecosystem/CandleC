use candlevm::opcode::Opcode;

pub(super) fn op_info(name: &str) -> Option<(u8, &'static [usize])> {
    Some(match name {
        "nop" => (Opcode::Nop as u8, &[]),
        "exit" => (Opcode::Exit as u8, &[0]),
        "ret" => (Opcode::Ret as u8, &[0]),
        "throw" => (Opcode::Throw as u8, &[0]),
        "inc" => (Opcode::Inc as u8, &[0]),
        "dec" => (Opcode::Dec as u8, &[0]),
        "arr_new" => (Opcode::NewArray as u8, &[0]),
        "map_new" => (Opcode::NewMap as u8, &[0]),
        "mov" => (Opcode::Mov as u8, &[0, 1]),
        "load_mod" => (Opcode::LoadModule as u8, &[0]),
        "load_global" => (Opcode::LoadGlobal as u8, &[0]),
        "load_res" => (Opcode::LoadResource as u8, &[0]),
        "store_global" => (Opcode::StoreGlobal as u8, &[1]),
        "type" => (Opcode::Type as u8, &[0, 0]),
        "obj_type" => (Opcode::ObjectType as u8, &[0, 0]),
        "add" => (Opcode::Add as u8, &[0, 1, 2]),
        "sub" => (Opcode::Sub as u8, &[0, 1, 2]),
        "mul" => (Opcode::Mul as u8, &[0, 1, 2]),
        "div" => (Opcode::Div as u8, &[0, 1, 2]),
        "mod" => (Opcode::Mod as u8, &[0, 1, 2]),
        "eq" => (Opcode::Eq as u8, &[0, 1, 2]),
        "ne" => (Opcode::Ne as u8, &[0, 1, 2]),
        "obj_eq" => (Opcode::ObjectEq as u8, &[0, 1, 2]),
        "obj_ne" => (Opcode::ObjectNe as u8, &[0, 1, 2]),
        "lt" => (Opcode::Lt as u8, &[0, 1, 2]),
        "lte" => (Opcode::Lte as u8, &[0, 1, 2]),
        "gt" => (Opcode::Gt as u8, &[0, 1, 2]),
        "gte" => (Opcode::Gte as u8, &[0, 1, 2]),
        "and" => (Opcode::And as u8, &[0, 1, 2]),
        "or" => (Opcode::Or as u8, &[0, 1, 2]),
        "xor" => (Opcode::Xor as u8, &[0, 1, 2]),
        "not" => (Opcode::Not as u8, &[0, 1]),
        "arr_len" => (Opcode::ArrayLen as u8, &[0, 1]),
        "arr_contains" => (Opcode::ArrayContains as u8, &[0, 1, 2]),
        "arr_get" => (Opcode::ArrayGet as u8, &[0, 1, 2]),
        "arr_set" => (Opcode::ArraySet as u8, &[0, 1, 2]),
        "arr_insert" => (Opcode::ArrayInsert as u8, &[0, 1, 2]),
        "arr_remove" => (Opcode::ArrayRemove as u8, &[0, 1]),
        "map_len" => (Opcode::MapLen as u8, &[0, 1]),
        "map_contains" => (Opcode::MapContains as u8, &[0, 1, 2]),
        "map_get" => (Opcode::MapGet as u8, &[0, 1, 2]),
        "map_set" => (Opcode::MapSet as u8, &[0, 1, 2]),
        "map_remove" => (Opcode::MapRemove as u8, &[0, 1]),
        "str_len" => (Opcode::StringLen as u8, &[0, 1]),
        "str_of" => (Opcode::StringOf as u8, &[0, 1]),
        "str_lowercase" => (Opcode::StringLowercase as u8, &[0, 1]),
        "str_uppercase" => (Opcode::StringUppercase as u8, &[0, 1]),
        "str_to_num" => (Opcode::StringToNumber as u8, &[0, 1]),
        "str_concat" => (Opcode::StringConcat as u8, &[0, 1, 2]),
        "str_from_chars" => (Opcode::StringFromChars as u8, &[0, 1]),
        "str_to_chars" => (Opcode::StringToChars as u8, &[0, 1]),
        "str_from_bytes" => (Opcode::StringFromBytes as u8, &[0, 1]),
        "str_to_bytes" => (Opcode::StringToBytes as u8, &[0, 1]),
        "err_type" => (Opcode::ErrorType as u8, &[0, 1]),
        "err_message" => (Opcode::ErrorMessage as u8, &[0, 1]),
        "buf_len" => (Opcode::BufferLen as u8, &[0, 1]),
        "buf_get" => (Opcode::BufferGet as u8, &[0, 1, 2]),
        "buf_set" => (Opcode::BufferSet as u8, &[0, 1, 2]),
        "buf_new" => (Opcode::NewBuffer as u8, &[0, 1]),
        "err_new" => (Opcode::NewError as u8, &[0, 1]),
        _ => return None,
    })
}
